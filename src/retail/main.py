"""Основной бизнес-процесс сети магазинов у дома."""

STAGES = [
    "Формирование ассортиментной матрицы",
    "Заключение договоров с поставщиками",
    "Централизованная закупка",
    "Доставка товара в магазины",
    "Приёмка и выкладка товара",
    "Ценообразование и проведение промоакций",
    "Продажа товара покупателю",
    "Учёт продаж и остатков",
    "Списание и возврат товара",
    "Формирование отчётности",
]


def main():
    print("Основной бизнес-процесс сети магазинов у дома:")
    for i, stage in enumerate(STAGES, 1):
        print(f"{i:>2}. {stage}")


if __name__ == "__main__":
    main()
